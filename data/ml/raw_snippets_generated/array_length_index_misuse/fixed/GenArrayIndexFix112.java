public class GenArrayIndexFix112 {
    static void showLast(int[] ratings) {
        System.out.println(ratings[ratings.length - 1]);
    }

    static int drain1(int points) {
        int handled = 0;
        while (points > 0) {
            handled += points;
            points--;
        }
        return handled;
    }

    static int clamp2(int value, int low, int high) {
        if (value < low) {
            return low;
        } else if (value > high) {
            return high;
        }
        return value;
    }
}
