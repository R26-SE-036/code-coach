public class GenIncorrectConditionalFix061 {
    static String report(boolean valid) {
        if (valid == true) {
            return "final";
        }
        return "closed";
    }

    static int clamp1(int value, int low, int high) {
        if (value < low) {
            return low;
        } else if (value > high) {
            return high;
        }
        return value;
    }

    static int clamp2(int value, int low, int high) {
        if (value < low) {
            return low;
        } else if (value > high) {
            return high;
        }
        return value;
    }
}
